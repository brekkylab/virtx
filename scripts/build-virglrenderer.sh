#!/bin/sh
# Build virglrenderer with venus (Vulkan) support for macOS hosts.
#
# Upstream virglrenderer forces the out-of-process render server on whenever
# venus is enabled, and that server is Linux-only (epoll, seccomp). The patch
# in 3rdparty/patches/ ports Sergio Lopez's in-process venus context -- the same work
# that krunkit's 0.10.4 fork carries -- onto upstream 1.3.0, which is the
# minimum version rutabaga_gfx (and therefore libkrun's `gpu` feature) accepts.
#
# The submodule itself is left pristine: the pinned tree is exported with
# `git archive` and patched in data/, so `git status` stays clean.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SUBMODULE="$ROOT/3rdparty/virglrenderer"
SRC="$ROOT/data/virglrenderer-src"
PREFIX="$ROOT/data/virglrenderer"
PATCH="$ROOT/3rdparty/patches/virglrenderer-1.3.0-macos-venus.patch"
VENV="$ROOT/data/meson-venv"

if [ ! -f "$SUBMODULE/meson.build" ]; then
    echo "virglrenderer submodule is not checked out." >&2
    echo "Run: git submodule update --init 3rdparty/virglrenderer" >&2
    exit 1
fi

for tool in meson ninja; do
    command -v "$tool" >/dev/null 2>&1 || { echo "missing $tool (brew install $tool)" >&2; exit 1; }
done

# MoltenVK is the Vulkan implementation on macOS, but it ships no vulkan.pc.
# Synthesise one so meson's dependency('vulkan') resolves; this replaces the
# hardcoded Homebrew paths the krunkit fork used.
MVK="$(brew --prefix molten-vk 2>/dev/null || echo /opt/homebrew/opt/molten-vk)"
if [ ! -f "$MVK/lib/libMoltenVK.dylib" ]; then
    echo "MoltenVK not found at $MVK (brew install molten-vk)" >&2
    exit 1
fi

# virglrenderer's gallium format tables are generated by a python script that
# needs PyYAML, which is usually not present in a Homebrew python.
if ! python3 -c 'import yaml' 2>/dev/null; then
    [ -d "$VENV" ] || python3 -m venv "$VENV"
    "$VENV/bin/pip" install -q pyyaml
    PYTHONPATH="$("$VENV/bin/python" -c 'import site; print(site.getsitepackages()[0])')"
    export PYTHONPATH
fi

echo "==> exporting pinned source ($(git -C "$SUBMODULE" rev-parse --short HEAD))"
rm -rf "$SRC"
mkdir -p "$SRC"
git -C "$SUBMODULE" archive --format=tar HEAD | tar -x -C "$SRC"

echo "==> applying $(basename "$PATCH")"
patch -p1 -s -d "$SRC" < "$PATCH"

PCDIR="$ROOT/data/pkgconfig"
mkdir -p "$PCDIR"
cat > "$PCDIR/vulkan.pc" <<PC
prefix=$MVK
Name: vulkan
Description: MoltenVK standing in for a Vulkan loader
Version: 1.4.0
Cflags: -I\${prefix}/libexec/include
Libs: -L\${prefix}/lib -lMoltenVK
PC

echo "==> configuring"
rm -rf "$PREFIX"
PKG_CONFIG_PATH="$PCDIR${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}" \
    meson setup "$SRC/build" "$SRC" \
        -Dvenus=true \
        -Drender-server=false \
        -Dvulkan-dload=false \
        --prefix="$PREFIX" \
        --buildtype=release >/dev/null

echo "==> building"
PKG_CONFIG_PATH="$PCDIR${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}" meson compile -C "$SRC/build" >/dev/null
PKG_CONFIG_PATH="$PCDIR${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}" meson install -C "$SRC/build" >/dev/null

# Keep everything consumers need behind a single PKG_CONFIG_PATH entry.
cp "$PCDIR/vulkan.pc" "$PREFIX/lib/pkgconfig/vulkan.pc"

echo
echo "installed to $PREFIX"
PKG_CONFIG_PATH="$PREFIX/lib/pkgconfig" pkg-config --modversion virglrenderer | sed 's/^/  virglrenderer /'
otool -L "$PREFIX/lib/libvirglrenderer.dylib" | grep -qi moltenvk && echo "  linked against MoltenVK"
echo
echo "build libkrun's gpu feature with:"
echo "  cargo build --features gpu"
