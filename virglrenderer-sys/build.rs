//! Build virglrenderer with venus (Vulkan) and tell the link where it is.
//!
//! On macOS this is the whole build: the pinned `3rdparty/virglrenderer` tree is exported
//! with `git archive` into `OUT_DIR`, patched there, configured with meson against MoltenVK
//! and installed under `OUT_DIR/install`. The submodule stays pristine.
//!
//! Upstream serves venus through its render server, and since 1.3.0 that server builds on
//! macOS and can run as a thread of the VMM (`render-server-mode=thread`), so no process is
//! forked or spawned. Memory reaches the guest as shm: MoltenVK imports it as an MTLBuffer
//! through VK_EXT_external_memory_metal, and virglrenderer exports the shm fd. The patch
//! carries the two things upstream main still gets wrong on macOS -- see the README.
//!
//! Every other host finds a virglrenderer that is already built through `pkg-config`: on
//! Windows the one `scripts/build-virglrenderer-windows.ps1` puts under `data/`, which
//! `.cargo/config.toml` points `PKG_CONFIG_PATH` at, and on Linux the system's.
//!
//! What reaches rutabaga_gfx's build script is `DEP_VIRGLRENDERER_PKGCONFIG`, the directory
//! its `pkg-config` probe should look in, set only when this script built the library.

use std::env;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::{self, Command, Stdio};

const PATCH: &str = "virglrenderer-8167744-macos.patch";

fn main() {
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        build_macos();
    } else {
        probe_prebuilt();
    }
}

fn probe_prebuilt() {
    println!("cargo:rerun-if-env-changed=PKG_CONFIG_PATH");
    if let Err(e) = pkg_config::Config::new()
        .atleast_version("1.3.0")
        .probe("virglrenderer")
    {
        die(&format!(
            "{e}\n\
             virglrenderer is built by this crate only on macOS. On Windows run\n\
             scripts/build-virglrenderer-windows.ps1 first; on Linux install the\n\
             virglrenderer development package."
        ));
    }
}

fn build_macos() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.parent().unwrap();
    let submodule = root.join("3rdparty/virglrenderer");
    let patch = root.join("3rdparty/_patches").join(PATCH);
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let src = out.join("src");
    let prefix = out.join("install");
    let pcdir = out.join("pkgconfig");

    if !submodule.join("meson.build").is_file() {
        die("virglrenderer submodule is not checked out.\n\
             Run: git submodule update --init 3rdparty/virglrenderer");
    }

    // A rerun is a full rebuild, so it is kept to what changes the result: the patch, and
    // the commit the submodule is on. HEAD of a submodule lives in the superproject's
    // `.git/modules/`, which `--git-path` resolves.
    println!("cargo:rerun-if-changed={}", patch.display());
    let head = output(Command::new("git").arg("-C").arg(&submodule).args([
        "rev-parse",
        "--git-path",
        "HEAD",
    ]));
    println!(
        "cargo:rerun-if-changed={}",
        submodule.join(head.trim()).display()
    );

    for tool in ["meson", "ninja"] {
        if Command::new(tool)
            .arg("--version")
            .stdout(Stdio::null())
            .status()
            .is_err()
        {
            die(&format!("missing {tool} (brew install {tool})"));
        }
    }

    // MoltenVK is the Vulkan implementation on macOS, but it ships no vulkan.pc. One is
    // synthesised so meson's dependency('vulkan') resolves and MoltenVK is linked rather
    // than dlopen()ed: `vulkan-dload` asks dyld for libvulkan.1.dylib or libMoltenVK.dylib
    // by leaf name, and Homebrew's lib directory is not on its default search path.
    let mvk = Command::new("brew")
        .args(["--prefix", "molten-vk"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_else(|| "/opt/homebrew/opt/molten-vk".into());
    if !Path::new(&mvk).join("lib/libMoltenVK.dylib").is_file() {
        die(&format!(
            "MoltenVK not found at {mvk} (brew install molten-vk)"
        ));
    }

    // Idempotent from here: whatever an earlier run left behind is started over.
    for dir in [&src, &prefix, &pcdir] {
        let _ = fs::remove_dir_all(dir);
        fs::create_dir_all(dir).unwrap();
    }

    // virglrenderer's gallium format tables are generated by a python script that needs
    // PyYAML, and venus-protocol's by one that needs Mako. Neither is usually present in a
    // Homebrew python.
    let mut pythonpath = None;
    if !Command::new("python3")
        .args(["-c", "import yaml, mako"])
        .stderr(Stdio::null())
        .status()
        .is_ok_and(|s| s.success())
    {
        let venv = out.join("venv");
        if !venv.join("bin/python").is_file() {
            run(Command::new("python3").args(["-m", "venv"]).arg(&venv));
        }
        run(Command::new(venv.join("bin/pip")).args(["install", "-q", "pyyaml", "mako"]));
        let site = output(
            Command::new(venv.join("bin/python"))
                .args(["-c", "import site; print(site.getsitepackages()[0])"]),
        );
        pythonpath = Some(site.trim().to_owned());
    }

    eprintln!("exporting the pinned source");
    let mut archive = Command::new("git")
        .arg("-C")
        .arg(&submodule)
        .args(["archive", "--format=tar", "HEAD"])
        .stdout(Stdio::piped())
        .spawn()
        .unwrap_or_else(|e| die(&format!("git: {e}")));
    run(Command::new("tar")
        .arg("-x")
        .arg("-C")
        .arg(&src)
        .stdin(archive.stdout.take().unwrap()));
    if !archive.wait().is_ok_and(|s| s.success()) {
        die("git archive failed");
    }

    eprintln!("applying {PATCH}");
    run(Command::new("patch")
        .args(["-p1", "-s", "-d"])
        .arg(&src)
        .stdin(fs::File::open(&patch).unwrap()));

    let vulkan_pc = format!(
        "prefix={mvk}\n\
         Name: vulkan\n\
         Description: MoltenVK standing in for a Vulkan loader\n\
         Version: 1.4.0\n\
         Cflags: -I${{prefix}}/libexec/include\n\
         Libs: -L${{prefix}}/lib -lMoltenVK\n"
    );
    fs::write(pcdir.join("vulkan.pc"), &vulkan_pc).unwrap();

    let meson = |args: &[&str]| {
        let mut cmd = Command::new("meson");
        cmd.args(args).env("PKG_CONFIG_PATH", join_path(&pcdir));
        if let Some(p) = &pythonpath {
            cmd.env("PYTHONPATH", p);
        }
        cmd
    };
    let build = src.join("build");
    let (src_s, build_s) = (src.to_str().unwrap(), build.to_str().unwrap());
    let prefix_opt = format!("--prefix={}", prefix.display());

    // venus-protocol is a meson subproject that is not in the exported tree; meson clones
    // it here, so this step needs git and the network.
    eprintln!("configuring");
    run(&mut meson(&[
        "setup",
        build_s,
        src_s,
        "-Dvenus=true",
        "-Drender-server-mode=thread",
        "-Drender-server-worker=thread",
        "-Dvulkan-dload=false",
        &prefix_opt,
        "--buildtype=release",
    ]));
    eprintln!("building");
    run(&mut meson(&["compile", "-C", build_s]));
    run(&mut meson(&["install", "-C", build_s]));

    // Everything rutabaga_gfx's probe needs, behind the one directory it is handed.
    let lib = prefix.join("lib");
    fs::write(lib.join("pkgconfig/vulkan.pc"), &vulkan_pc).unwrap();

    println!("cargo:rustc-link-search=native={}", lib.display());
    println!("cargo:rustc-link-lib=dylib=virglrenderer");
    println!("cargo:root={}", prefix.display());
    println!("cargo:pkgconfig={}", lib.join("pkgconfig").display());
}

/// `PKG_CONFIG_PATH` with `dir` in front of whatever the environment already had.
fn join_path(dir: &Path) -> std::ffi::OsString {
    let rest = env::var_os("PKG_CONFIG_PATH");
    env::join_paths(
        std::iter::once(dir.to_path_buf()).chain(rest.iter().flat_map(env::split_paths)),
    )
    .unwrap()
}

/// Run `cmd` with its stdout sent to stderr: this script's stdout is what cargo reads
/// `cargo:` lines from, and meson's chatter belongs in the build log with the rest.
fn run(cmd: &mut Command) {
    let status = cmd
        .stdout(io::stderr())
        .status()
        .unwrap_or_else(|e| die(&format!("{:?}: {e}", cmd.get_program())));
    if !status.success() {
        die(&format!("{cmd:?} failed with {status}"));
    }
}

fn output(cmd: &mut Command) -> String {
    let out = cmd
        .output()
        .unwrap_or_else(|e| die(&format!("{:?}: {e}", cmd.get_program())));
    if !out.status.success() {
        die(&format!("{cmd:?} failed with {}", out.status));
    }
    String::from_utf8(out.stdout).unwrap()
}

fn die(msg: &str) -> ! {
    eprintln!("error: {msg}");
    process::exit(1);
}
